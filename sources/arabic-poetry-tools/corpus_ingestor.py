def clean_arabic(text: str) -> str:
    """Normalizes Arabic text for consistent indexing."""
    t = text.strip()
    # Normalize alefs
    t = re.sub(r'[إأآٱ]', 'ا', t)
    # Normalize ya
    t = re.sub(r'ى', 'ي', t)
    # Remove excessive tatweel
    t = re.sub(r'ـ+', '', t)
    return t

